def q(s):
    if s is None:
        return "NULL"
    if isinstance(s, bool):
        return "1" if s else "0"
    if isinstance(s, int):
        return str(s)
    if isinstance(s, float):
        return "%.2f" % s
    return "'" + str(s).replace("\\", "\\\\").replace("'", "''") + "'"

def add_h(s, hours):
    return (datetime.strptime(s, "%Y-%m-%d %H:%M:%S") + timedelta(hours=hours)).strftime("%Y-%m-%d %H:%M:%S")

def add_m(s, minutes):
    return add_h(s, minutes / 60.0)

def ins(table, cols, rows):
    if not rows:
        return ""
    for r in rows:
        if len(r) != len(cols):
            raise SystemExit("column/value mismatch: %s cols=%d vals=%d row=%r" % (table, len(cols), len(r), r))
    head = "INSERT INTO `%s` (%s) VALUES\n" % (table, ", ".join("`%s`" % c for c in cols))
    body = ",\n".join("(" + ", ".join(q(v) for v in r) + ")" for r in rows)
    return head + body + ";"

